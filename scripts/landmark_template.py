#!/usr/bin/env python3
"""Promote the landmarks from barycentric addresses to real template vertices.

MediaPipe's canonical face mesh has a property ours lacked: vertex i IS
landmark i. The network's output is the mesh. Ours came the other way round --
the template was fitted by Wrap and the landmarks were painted onto its faces
as (triangle, u, v) -- so a landmark was a sparse READOUT of the mesh and could
never be a vertex of it.

This inserts each mark into the template as an actual vertex and renumbers so
the marks are vertices 0..k-1, leaving the surface geometrically unchanged: a
point already on a face is added by splitting that face, which moves nothing.

The insertion is recorded as a RECIPE against the ORIGINAL topology, so it
replays on every fit in the corpus -- they all share that topology -- without
re-running anything upstream.

    python scripts/landmark_template.py            # writes the new template
    python scripts/landmark_template.py --replay corpus/canonical_esc/hutubs
"""
import argparse
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
WRAP = ROOT.parent / "wrap_work"
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from ear3d.wrap import load_mesh                       # noqa: E402

# A mark this close to an edge in barycentric terms is treated as ON the edge.
# Splitting a face at an interior point that is 0.008 of the way across makes a
# sliver whose normal is numerically meaningless; splitting the EDGE instead
# costs a displacement of about a hundredth of a millimetre. Measured and
# reported below rather than assumed -- that is the whole trade.
# Set at run time from --edge-tol / --snap-budget; 0 disables snapping and
# keeps every landmark exactly where the marks put it, at the cost of a sliver
# triangle wherever a mark sits close to an edge. Which of those costs more is
# measured (triangle quality here, flip robustness under --replay), not assumed.
EDGE_TOL = 0.02
SNAP_TOL_MM = 0.05          # refuse if snapping moves a mark more than this


def place(V, F, tri, bary):
    return np.einsum("ij,ijk->ik", bary, V[F[tri]])


def write_obj(path, V, F):
    with open(path, "w") as f:
        f.write("# landmark-vertex ear template, generated by "
                "scripts/landmark_template.py\n")
        for p in V:
            f.write(f"v {p[0]:.6f} {p[1]:.6f} {p[2]:.6f}\n")
        for t in F:
            f.write(f"f {t[0]+1} {t[1]+1} {t[2]+1}\n")


def snap(tri, bary, V, F):
    """Move marks that sit within EDGE_TOL of an edge onto that edge.

    Returns (bary, on_edge, moved_mm). on_edge[j] is the local edge index
    0=(a,b) 1=(b,c) 2=(c,a), or -1 for an interior mark.
    """
    bary = bary.copy()
    before = place(V, F, tri, bary)
    on_edge = np.full(len(tri), -1)
    for j in range(len(tri)):
        k = int(np.argmin(bary[j]))
        if bary[j, k] < EDGE_TOL:
            bary[j, k] = 0.0
            bary[j] /= bary[j].sum()
            # corner k is opposite the edge joining the other two corners:
            # k=0 -> (b,c)=edge 1, k=1 -> (c,a)=edge 2, k=2 -> (a,b)=edge 0
            on_edge[j] = (k + 1) % 3
    moved = np.linalg.norm(place(V, F, tri, bary) - before, axis=1)
    return bary, on_edge, moved


def _rot(corners, splits, n):
    """Rotate a triangle's corners n times; edge i moves to edge i-n."""
    c = corners[n:] + corners[:n]
    s = splits[n:] + splits[:n]
    return c, s


def retriangulate(tri_corners, interior, edge_splits):
    """One original triangle -> its sub-triangles.

    tri_corners: (a, b, c) new-mesh vertex ids, in the original winding.
    interior: a vertex id for a point strictly inside, or None.
    edge_splits: [e0, e1, e2], a vertex id or None per edge, where edge 0 is
    (a,b), edge 1 is (b,c), edge 2 is (c,a).

    Every rule below keeps the original winding, so the sub-triangles inherit
    the parent's orientation; that is checked against the parent normal later.
    """
    a, b, c = tri_corners
    e = list(edge_splits)
    if interior is not None:
        # Fan from the interior point over the boundary polygon. Each original
        # edge contributes one segment, or two if it carries a split point.
        poly = []
        for u, v, s in ((a, b, e[0]), (b, c, e[1]), (c, a, e[2])):
            poly.append(u)
            if s is not None:
                poly.append(s)
        return [(interior, poly[i], poly[(i + 1) % len(poly)])
                for i in range(len(poly))]

    k = sum(x is not None for x in e)
    if k == 0:
        return [(a, b, c)]
    if k == 1:
        n = [i for i, x in enumerate(e) if x is not None][0]
        (a, b, c), e = _rot([a, b, c], e, n)      # split now on edge 0 = (a,b)
        return [(a, e[0], c), (e[0], b, c)]
    if k == 2:
        # rotate so the two splits are on edges 0 and 1
        miss = [i for i, x in enumerate(e) if x is None][0]
        (a, b, c), e = _rot([a, b, c], e, (miss + 1) % 3)
        return [(e[0], b, e[1]), (a, e[0], e[1]), (a, e[1], c)]
    return [(a, e[0], e[2]), (e[0], b, e[1]), (e[2], e[1], c),
            (e[0], e[1], e[2])]


def build(V, F, tri, bary):
    """Insert the marks and renumber so mark j is vertex j.

    Returns V2, F2, perm, recipe where perm[i] is the ORIGINAL vertex index of
    new vertex i (-1 for an inserted one) and recipe carries what is needed to
    replay the same insertion on another mesh of the same topology.
    """
    k = len(tri)
    bary, on_edge, moved = snap(tri, bary, V, F)
    if moved.max() > SNAP_TOL_MM:
        sys.exit(f"snapping a mark to its edge would move it "
                 f"{moved.max():.4f} mm, over the {SNAP_TOL_MM} mm budget")
    L = place(V, F, tri, bary)

    # New numbering: marks first, then the original vertices in order. Nothing
    # else is appended at this stage -- an edge split reuses the mark itself as
    # the new edge vertex, so the mark count IS the vertex growth.
    V2 = np.vstack([L, V])
    perm = np.concatenate([np.full(k, -1), np.arange(len(V))])
    new_of_old = np.arange(len(V)) + k

    interior = {}
    esplit = {}                      # (original triangle, local edge) -> vid
    for j in range(k):
        t = int(tri[j])
        if on_edge[j] < 0:
            if t in interior:
                sys.exit(f"triangle {t} already carries an interior mark; "
                         f"this build assumes one per face")
            interior[t] = j
        else:
            esplit[(t, int(on_edge[j]))] = j

    # An edge split must be seen by BOTH incident triangles or the mesh tears.
    # Map each undirected edge to the (triangle, local edge) slots on it.
    slots = {}
    for t, f in enumerate(F):
        for i in range(3):
            key = tuple(sorted((int(f[i]), int(f[(i + 1) % 3]))))
            slots.setdefault(key, []).append((t, i))
    shared = {}
    for (t, i), j in list(esplit.items()):
        key = tuple(sorted((int(F[t, i]), int(F[t, (i + 1) % 3]))))
        for slot in slots[key]:
            shared[slot] = j

    F2 = []
    parent = []
    for t, f in enumerate(F):
        corners = tuple(new_of_old[f])
        e = [shared.get((t, i)) for i in range(3)]
        out = retriangulate(corners, interior.get(t), e)
        F2 += out
        parent += [t] * len(out)
    F2 = np.asarray(F2, dtype=np.int64)
    recipe = dict(insert_tri=tri, insert_bary=bary, on_edge=on_edge,
                  perm=perm, faces=F2, parent=np.asarray(parent),
                  snap_moved_mm=moved)
    return V2, F2, perm, recipe


def replay(V, recipe):
    """Apply a stored insertion to another mesh of the ORIGINAL topology."""
    L = place(V, recipe["F_orig"], recipe["insert_tri"], recipe["insert_bary"])
    return np.vstack([L, V])


def vertex_bary(F2, k):
    """A barycentric address on the NEW mesh for each landmark vertex.

    Trivial by construction -- weight 1 at the corner -- but the corpus tooling
    speaks (triangle, u, v), so keeping that interface means propagation,
    the viewer and the scorer all keep working unchanged.
    """
    tri = np.full(k, -1, dtype=np.int64)
    bary = np.zeros((k, 3))
    for t, f in enumerate(F2):
        for i in range(3):
            j = int(f[i])
            if j < k and tri[j] < 0:
                tri[j], bary[j, i] = t, 1.0
    if (tri < 0).any():
        sys.exit(f"landmark vertices {np.flatnonzero(tri < 0).tolist()} are in "
                 f"no face -- the retriangulation dropped them")
    return tri, bary


def check(V, F, V2, F2, recipe, L_want, verbose=True):
    """Everything that must hold, stated as numbers rather than hoped for."""
    k = len(L_want)
    bad = []

    def area_normals(Vx, Fx):
        p = Vx[Fx]
        n = np.cross(p[:, 1] - p[:, 0], p[:, 2] - p[:, 0])
        return 0.5 * np.linalg.norm(n, axis=1), n

    a0, n0 = area_normals(V, F)
    a1, n1 = area_normals(V2, F2)
    # 1. the surface is unchanged: total area, to floating point
    da = abs(a1.sum() - a0.sum()) / a0.sum()
    if da > 1e-9:
        bad.append(f"total area changed by {da:.2e} relative")
    # 2. no degenerate triangle
    if a1.min() <= 0:
        bad.append(f"{int((a1 <= 0).sum())} zero-area triangles")
    # 3. every sub-triangle keeps its parent's orientation
    par = recipe["parent"]
    cos = np.einsum("ij,ij->i", n1, n0[par])
    nrm = np.linalg.norm(n1, axis=1) * np.linalg.norm(n0[par], axis=1)
    cos = cos / np.maximum(nrm, 1e-30)
    if cos.min() < 0.999:
        bad.append(f"{int((cos < 0.999).sum())} sub-triangles disagree with "
                   f"their parent's normal (min cos {cos.min():.6f})")
    # 4. the landmarks really are the first k vertices
    err = np.abs(V2[:k] - L_want).max()
    if err > 1e-9:
        bad.append(f"landmark vertices differ from the marks by {err:.2e} mm")
    # 5. the original vertices survive, in order, unmoved
    perm = recipe["perm"]
    keep = perm >= 0
    if not np.array_equal(perm[keep], np.arange(len(V))):
        bad.append("original vertices were reordered")
    elif np.abs(V2[keep] - V).max() > 0:
        bad.append("original vertices moved")
    # 6. the mesh is still a manifold with the same boundary
    def boundary_len(Fx):
        c = {}
        for f in Fx:
            for i in range(3):
                key = tuple(sorted((int(f[i]), int(f[(i + 1) % 3]))))
                c[key] = c.get(key, 0) + 1
        return sum(1 for v in c.values() if v == 1), max(c.values())
    b0, m0 = boundary_len(F)
    b1, m1 = boundary_len(F2)
    if m1 > 2:
        bad.append(f"non-manifold: an edge is shared by {m1} faces")
    if verbose:
        q = 4 * np.sqrt(3) * a1 / np.array(
            [np.sum(np.linalg.norm(np.diff(V2[f][[0, 1, 2, 0]], axis=0),
                                   axis=1) ** 2) for f in F2])
        print(f"  vertices {len(V)} -> {len(V2)}   faces {len(F)} -> {len(F2)}")
        print(f"  total area {a0.sum():.4f} -> {a1.sum():.4f} mm^2 "
              f"(relative change {da:.1e})")
        print(f"  smallest triangle {a0.min():.2e} -> {a1.min():.2e} mm^2")
        print(f"  triangle quality (1 = equilateral): median {np.median(q):.3f}"
              f"  min {q.min():.4f}  (original median "
              f"{np.median(4 * np.sqrt(3) * a0 / np.array([np.sum(np.linalg.norm(np.diff(V[f][[0, 1, 2, 0]], axis=0), axis=1) ** 2) for f in F])):.3f})")
        print(f"  boundary edges {b0} -> {b1}   max faces per edge {m1}")
        mv = recipe["snap_moved_mm"]
        print(f"  {int((recipe['on_edge'] >= 0).sum())} marks snapped to an "
              f"edge, moving them at most {mv.max():.4f} mm "
              f"(median of those moved {np.median(mv[mv > 0]):.4f} mm)")
    return bad


def main():
    global EDGE_TOL, SNAP_TOL_MM
    p = argparse.ArgumentParser()
    p.add_argument("--template", default=str(WRAP / "templates/ear_mean_v4.obj"))
    p.add_argument("--marks", default=str(
        WRAP / "templates/mark_mean_v6_spacing.wrap"))
    p.add_argument("--n-points", type=int, default=55)
    p.add_argument("--edge-tol", type=float, default=EDGE_TOL,
                   help="treat a mark within this barycentric distance of an "
                        "edge as lying ON it. 0 keeps every mark exactly "
                        "where it is and accepts the sliver")
    p.add_argument("--snap-budget", type=float, default=SNAP_TOL_MM,
                   help="refuse if --edge-tol would move a mark further (mm)")
    p.add_argument("--out", default=str(WRAP / "templates/ear_lmv_v3.obj"))
    p.add_argument("--recipe", default=str(WRAP / "templates/ear_lmv_v3.npz"))
    p.add_argument("--replay", nargs="*", default=[],
                   help="directories of fits sharing the template topology; "
                        "each is converted and checked, nothing is written")
    a = p.parse_args()

    from gt_landmark_check import read_marks

    EDGE_TOL, SNAP_TOL_MM = a.edge_tol, a.snap_budget

    V, F = load_mesh(a.template)
    tri, bary, names = read_marks(a.marks)
    tri, bary = tri[:a.n_points], bary[:a.n_points]
    names = [str(x) for x in names[:a.n_points]]
    print(f"{a.template}\n  {len(V)} vertices, {len(F)} faces")
    print(f"{a.marks}\n  {len(tri)} marks")

    # Computed from the ORIGINAL mesh, independently of build(), so the
    # check below compares two separate derivations rather than an array
    # with itself.
    L_want = place(V, F, tri, snap(tri, bary, V, F)[0])
    V2, F2, perm, recipe = build(V, F, tri, bary)
    print("\npromoting the marks to vertices:")
    bad = check(V, F, V2, F2, recipe, L_want)
    ntri, nbary = vertex_bary(F2, len(tri))
    back = place(V2, F2, ntri, nbary)
    print(f"  recomputed barycentrics reproduce the landmarks to "
          f"{np.abs(back - V2[:len(tri)]).max():.2e} mm")
    if bad:
        print("\nFAILED:")
        for m in bad:
            print("  -", m)
        sys.exit(1)

    write_obj(a.out, V2, F2)
    np.savez_compressed(
        a.recipe, insert_tri=recipe["insert_tri"],
        insert_bary=recipe["insert_bary"], on_edge=recipe["on_edge"],
        perm=perm, faces=F2, parent=recipe["parent"],
        F_orig=F, triangle=ntri, barycentric=nbary,
        names=np.array(names), n_landmarks=len(tri),
        template=str(a.template), marks=str(a.marks))
    print(f"\nwrote {a.out}\n      {a.recipe}")

    for d in a.replay:
        files = sorted(pathlib.Path(d).glob("*.obj"))
        worst = (1e9, "")
        fails = []
        for f in files:
            Vf, Ff = load_mesh(f)
            if len(Vf) != len(V) or not np.array_equal(Ff, F):
                fails.append(f"{f.name}: topology differs from the template")
                continue
            V2f = np.vstack([place(Vf, F, recipe["insert_tri"],
                                   recipe["insert_bary"]), Vf])
            pt = V2f[F2]
            n = np.cross(pt[:, 1] - pt[:, 0], pt[:, 2] - pt[:, 0])
            ar = 0.5 * np.linalg.norm(n, axis=1)
            n0 = np.cross(Vf[Ff][:, 1] - Vf[Ff][:, 0],
                          Vf[Ff][:, 2] - Vf[Ff][:, 0])
            cs = np.einsum("ij,ij->i", n, n0[recipe["parent"]]) / np.maximum(
                np.linalg.norm(n, axis=1)
                * np.linalg.norm(n0[recipe["parent"]], axis=1), 1e-30)
            if ar.min() <= 0 or cs.min() < 0.999:
                fails.append(f"{f.name}: min area {ar.min():.2e}, "
                             f"min parent cos {cs.min():.4f}")
            if cs.min() < worst[0]:
                worst = (cs.min(), f.name)
        print(f"\nreplay on {d}: {len(files)} fits, {len(fails)} failures; "
              f"worst parent-normal cos {worst[0]:.6f} on {worst[1]}")
        for m in fails[:10]:
            print("  -", m)


if __name__ == "__main__":
    main()
